/**
 * Get translated text for a given language code and key.
 * Falls back to English if translation is missing.
 */
export function t(lang: string, key: TranslationKey, fallback?: string): string {
  const langKey = lang?.toLowerCase() || 'en';
  const langDict = translations[langKey] || translations['en'];
  return langDict[key] || translations['en'][key] || fallback || key;
}

/**
 * Get language object by code
 */
export function getLanguageOption(code: string): LanguageOption {
  return (
    SUPPORTED_LANGUAGES.find(l => l.code === code) ||
    SUPPORTED_LANGUAGES.find(l => l.name.toLowerCase() === code.toLowerCase()) ||
    SUPPORTED_LANGUAGES[0]
  );
}
